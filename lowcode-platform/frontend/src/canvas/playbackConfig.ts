// Настройки скорости "проигрывания" событий исполнения на канвасе.
// Раньше события применялись к состоянию мгновенно по мере прихода с backend
// (а тот публикует их практически без задержек между шагами) — на глаз это
// выглядело как мгновенная вспышка, а не анимация. Теперь события идут через
// очередь и применяются по одному с паузой между ними (см. SchemeCanvas —
// eventQueueRef/pump), а вот эта пауза настраивается.
//
// Поменяйте DEFAULT_STEP_DELAY_MS, если хотите другой дефолт "из коробки" —
// в самом UI (панель запуска, слайдер) это крутится на лету без перезагрузки.
export const MIN_STEP_DELAY_MS = 100;
export const MAX_STEP_DELAY_MS = 3000;
export const DEFAULT_STEP_DELAY_MS = 900;
