-- Порядковый номер запуска в рамках одного сценария (запрос из UI: "Запуск #N"
-- в статусе завершения) — считается на бэке, а не на фронте, чтобы переживать
-- перезагрузку страницы/открытие в новой вкладке. Гонка при вычислении
-- max+1 в RunService возможна при параллельном старте одного и того же
-- сценария — для демо-инструмента приемлемо (тот же trade-off, что и в ревью
-- backend про order_index).
alter table execution_run
    add column run_number int not null default 1;
